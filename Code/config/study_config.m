function cfg = study_config(dataRoot, derivativesRoot)
%STUDY_CONFIG Configure data, software and analysis output locations.
codeRoot = fileparts(fileparts(mfilename('fullpath')));
if nargin < 1 || isempty(dataRoot), dataRoot = fullfile(fileparts(codeRoot), 'Data'); end
if nargin < 2 || isempty(derivativesRoot), derivativesRoot = fullfile(fileparts(codeRoot), 'derivatives'); end
cfg.code_root = codeRoot;
cfg.data_root = dataRoot;
cfg.derivatives_root = derivativesRoot;
cfg.output_root = fullfile(codeRoot, 'outputs');
cfg.spm_dir = getenv('SPM_DIR');
cfg.dpabi_dir = getenv('DPABI_DIR');
cfg.dpabi_config_file = fullfile(derivativesRoot, 'preprocessing', 'dpabi_config.mat');
cfg.subject_list = fullfile(codeRoot, 'config', 'subjects.txt');
cfg.participant_csv = fullfile(codeRoot, 'config', 'participants.csv');
cfg.image_id_csv = fullfile(codeRoot, 'config', 'image_id.csv');
cfg.canonical_image_csv = cfg.image_id_csv;
cfg.canonical_image_column = 'File_Name';
cfg.preprocessed_root = fullfile(derivativesRoot, 'preprocessed');
cfg.conditions_root = fullfile(derivativesRoot, 'conditions');
cfg.first_level_root = fullfile(derivativesRoot, 'activation_first_level');
cfg.activation_root = fullfile(derivativesRoot, 'activation_group');
cfg.lss_root = fullfile(derivativesRoot, 'lss');
cfg.connectivity_root = fullfile(derivativesRoot, 'connectivity');
cfg.merged_atlas_dir = fullfile(derivativesRoot, 'atlas');
cfg.hcpex_source_atlas = fullfile(codeRoot, 'external', 'HCPex', 'HCPex.nii');
cfg.hcpex_atlas = fullfile(cfg.merged_atlas_dir, 'HCPex_MergedROI_UrbanPerception_Refined17_Bilateral_2mm.nii');
cfg.hcpex_labels = fullfile(codeRoot, 'config', 'hcpex_merged_lookup.csv');
cfg.atlas_crosswalk = fullfile(codeRoot, 'config', 'hcpex_parcel_crosswalk.xlsx');
cfg.urban_feature_csv = fullfile(codeRoot, 'external', 'features', 'urban_features.csv');
cfg.urban_rdm_dir = fullfile(derivativesRoot, 'urban_rdms');
cfg.lss_run_manifest = fullfile(derivativesRoot, 'lss', 'lss_run_manifest.csv');
cfg.rsa_run_manifest = fullfile(derivativesRoot, 'rsa_patterns', 'rsa_run_manifest.csv');
cfg.rsa_expected_trials = 99;
cfg.rsa_require_expected_trials = true;
cfg.TR = 1;
cfg.n_slices = 60;
cfg.slice_order = [];
cfg.reference_slice = 30;
cfg.n_trials = 99;
cfg.fd_threshold = 0.5;
cfg.groups = {'Group1','Group2','Group3','Group4'};
cfg.runs = {'Run1','Run2','Run3','Run4'};
end
